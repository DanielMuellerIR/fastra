// FourDTokenizer scannt UTF-16-Zellen; Surrogate bleiben deshalb keine Namenszeichen.
pub(super) fn properties(c: char) -> u8 {
    if c.is_ascii() {
        return if c.is_ascii_alphabetic() {
            1
        } else if c.is_ascii_digit() {
            10
        } else if matches!(c, ' ' | '\t') {
            4
        } else {
            0
        };
    }
    let value = c as u32;
    let i = RANGES.partition_point(|&(_, end, _)| end < value);
    RANGES
        .get(i)
        .filter(|&&(start, _, _)| start <= value)
        .map_or(0, |&(_, _, flags)| flags)
}
